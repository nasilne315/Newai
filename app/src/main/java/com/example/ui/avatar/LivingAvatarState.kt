    CLAPPING,         // Rhythmic clapping hands meeting in center
    PEACE_SIGN,       // Peace/Victory V sign with index & middle fingers
    OK_SIGN,          // Precision OK sign with thumb & index circle
    POINTING_UP,      // Index finger raised pointing up/directing
    POINTING_AT_USER, // Index finger pointing toward user/cursor
    PALMS_UP,         // Warm open upturned palms explaining
    FIST_BUMP,        // Confident closed fist held forward
    CHEEK_TOUCH,      // Raised, cradling cheek (surprised)
    SHRUG,            // Raised slightly, tilted outward shrug
    THUMBS_UP,        // Raised, thumbs up fist
    COVER_MOUTH,      // Raised, covering mouth giggling
    HEART_SIDE,       // Meeting in center forming heart
    SLEEPY_RUB,       // Curled hand gently rubbing eye
    TYPING_MIMIC      // Air-typing finger flutter while reading user input
}

